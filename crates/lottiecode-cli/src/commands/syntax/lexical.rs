//! 词法章节：注释、字面量、标识符、标点。

pub const SECTION: &str = r#"## 词法

**注释：** `// 行注释`（暂无块注释）。

**标识符：** `[A-Za-z_][A-Za-z0-9_-]*` —— **允许连字符**，例如 `ease-out-back`、`trim-end`、`outer-radius`、`char-opacity`。

**字面量：**

| 类型     | 写法                                | 备注 |
|----------|-------------------------------------|---|
| 整数     | `100`、`-30`                         | i64 |
| 浮点     | `33.333`、`-1.5`                     | f64 |
| 布尔     | `true` / `false`                     | 关键字 |
| 字符串   | `"Hello"`                            | 双引号，无插值 |
| 颜色     | `#RRGGBB` 或 `#RRGGBBAA`              | 6 或 8 位十六进制 |
| 时间     | `0.5s` / `500ms` / `30f`              | f = 帧，按当前 fps 换算为秒 |
| 数组     | `[1, 2, 3]` 或 `[[x,y], [x,y]]`        | 元素为表达式；逗号可省 |
| 对象     | `{ key = value, ... }`                | 块属性集；逗号可省 |
| 标识符值 | `bold` / `round` / `center` / `star`  | 用作枚举 |
| 点路径   | `color.success` / `slot.foo`          | token / slot / component-arg 引用 |

**标点：** `{ } ( ) [ ] = , . : +`

**纯数字时间**：未带 `s/ms/f` 后缀的数字会被当作秒，例如 `duration = 2`（= 2 秒）。建议总是写明单位。
"#;
